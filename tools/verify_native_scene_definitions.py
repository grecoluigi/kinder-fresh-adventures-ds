"""Check regenerated native definitions against expected assets and reject malformed files."""
from pathlib import Path
import argparse, hashlib, json, struct, subprocess, tempfile

R=Path(__file__).resolve().parents[1]
H=R/'ds/source/native_scene_definition.h'
C=r'''
#include "native_scene_definition.h"
#include <assert.h>
int main(int argc,char **argv){
 assert(argc>=3);NativeSceneDefinition d={0};
 assert(native_scene_definition_open(&d,argv[1]));
 if(!strcmp(argv[2],"dump")){
  printf("%u %u %u %u %u %u\n",d.native_width,d.native_height,d.width,d.height,d.static_orders,d.event_count);
  for(unsigned i=0;i<d.event_count;i++)printf("%u %u %u\n",d.events[i].kind,d.events[i].order,d.events[i].argument);
 }else{
  NativeSceneDefinition saved=d;NativeSceneEvent *events=malloc(d.event_count*sizeof(*events));
  assert(events);memcpy(events,d.events,d.event_count*sizeof(*events));
  assert(!native_scene_definition_open(&d,NULL));
  for(int i=2;i<argc;i++){
   assert(!native_scene_definition_open(&d,argv[i]));
   assert(!memcmp(&d,&saved,sizeof(d))&&!memcmp(d.events,events,d.event_count*sizeof(*events)));
  }
  free(events);
 }
 native_scene_definition_close(&d);native_scene_definition_close(&d);return 0;
}
'''
def main():
 global H
 parser=argparse.ArgumentParser(description=__doc__)
 parser.add_argument('--assets',type=Path,default=R/'ds/nitrofs/native_scenery')
 parser.add_argument('--expected-assets',type=Path,default=R/'ds/nitrofs/native_scenery',help='Expected native definitions (default: current playable assets)')
 parser.add_argument('--output',type=Path,default=R/'build/verifications/native-scene-definitions.json')
 args=parser.parse_args();assets=args.assets;callbacks=0
 actual={p.name for p in assets.glob('*.nsc')};expected_files={p.name for p in args.expected_assets.glob('*.nsc')}
 if not actual or actual!=expected_files:parser.error('Native definition inventories must match and be nonempty')
 with tempfile.TemporaryDirectory(prefix='kinder-native-def-')as directory:
  root=Path(directory);source=root/'check.c';source.write_text(C);exe=root/'check'
  subprocess.run(['cc','-Wall','-Wextra','-Werror','-O1','-g','-fsanitize=address,undefined','-fno-sanitize-recover=all','-I'+str(H.parent),str(source),'-o',str(exe)],check=True)
  for path in sorted(assets.glob('*.nsc')):
   lines=subprocess.check_output([str(exe),str(path),'dump'],text=True).splitlines()
   native_w,native_h,w,h,orders,count=map(int,lines[0].split())
   expected_blob=(args.expected_assets/path.name).read_bytes()
   assert path.read_bytes()==expected_blob,(path.name,'regenerated bytes differ')
   magic,nw,nh,ew,eh,eo,ec,flags=struct.unpack_from('<4s7I',expected_blob)
   assert magic==b'KNS1' and not flags
   assert (native_w,native_h,w,h,orders,count)==(nw,nh,ew,eh,eo,ec)
   expected=[]
   for kind,ordinal,reserved,argument in struct.iter_unpack('<BBHI',expected_blob[32:]):
    assert not reserved
    expected.append((kind,ordinal,argument))
   assert [tuple(map(int,line.split()))for line in lines[1:]]==expected
   assert count==len(expected);callbacks+=count
  valid=next(assets.glob('*.nsc'));blob=valid.read_bytes();invalid=[]
  for length in [0,3,4,16,31,32,len(blob)-1]:invalid.append(blob[:length])
  invalid.extend([blob+b'X',b'BAD!'+blob[4:]])
  for offset,value in [(4,799),(8,599),(12,255),(16,191),(20,0),(20,256),(24,4097),(28,1)]:
   data=bytearray(blob);struct.pack_into('<I',data,offset,value);invalid.append(bytes(data))
  for offset,value in [(32,0),(32,3),(33,255),(34,1),(35,1)]:
   data=bytearray(blob);data[offset]=value;invalid.append(bytes(data))
  # Two callbacks with decreasing order must fail even when each order fits.
  data=bytearray(blob);data[33]=1;data[41]=0;invalid.append(bytes(data))
  paths=[]
  for i,data in enumerate(invalid):
   path=root/(str(i)+'.bad');path.write_bytes(data);paths.append(str(path))
  subprocess.run([str(exe),str(valid),*paths],check=True)
 report=dict(scope=__doc__,maps=len(actual),callbacks=callbacks,malformed_files=len(invalid),
             retained_state_on_failure=True,sanitizers=['address','undefined'],
             source_sha256=hashlib.sha256(H.read_bytes()).hexdigest(),
             limits=['Standalone metadata loader, not integrated gameplay or a performance proof.'])
 args.output.parent.mkdir(parents=True,exist_ok=True)
 args.output.write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report))
if __name__=='__main__':main()
